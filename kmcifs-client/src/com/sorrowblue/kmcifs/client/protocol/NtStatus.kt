package com.sorrowblue.kmcifs.client.protocol

/**
 * Common `NTSTATUS` status codes returned in SMB2/SMB3 headers (`[MS-ERREF] 2.3`).
 */
object NtStatus {
    const val STATUS_SUCCESS: UInt = 0x00000000u
    const val STATUS_PENDING: UInt = 0x00000103u
    const val STATUS_NOTIFY_CLEANUP: UInt = 0x0000010Bu
    const val STATUS_NOTIFY_ENUM_DIR: UInt = 0x0000010Cu

    const val STATUS_BUFFER_OVERFLOW: UInt = 0x80000005u
    const val STATUS_NO_MORE_FILES: UInt = 0x80000006u

    const val STATUS_INVALID_PARAMETER: UInt = 0xC000000Du
    const val STATUS_NO_SUCH_FILE: UInt = 0xC000000Fu
    const val STATUS_END_OF_FILE: UInt = 0xC0000011u
    const val STATUS_MORE_PROCESSING_REQUIRED: UInt = 0xC0000016u
    const val STATUS_ACCESS_DENIED: UInt = 0xC0000022u
    const val STATUS_BUFFER_TOO_SMALL: UInt = 0xC0000023u
    const val STATUS_OBJECT_NAME_INVALID: UInt = 0xC0000033u
    const val STATUS_OBJECT_NAME_NOT_FOUND: UInt = 0xC0000034u
    const val STATUS_OBJECT_NAME_COLLISION: UInt = 0xC0000035u
    const val STATUS_OBJECT_PATH_NOT_FOUND: UInt = 0xC000003Au
    const val STATUS_SHARING_VIOLATION: UInt = 0xC0000043u
    const val STATUS_FILE_LOCK_CONFLICT: UInt = 0xC0000054u
    const val STATUS_LOCK_NOT_GRANTED: UInt = 0xC0000055u
    const val STATUS_LOGON_FAILURE: UInt = 0xC000006Du
    const val STATUS_ACCOUNT_RESTRICTION: UInt = 0xC000006Eu
    const val STATUS_PASSWORD_EXPIRED: UInt = 0xC0000071u
    const val STATUS_ACCOUNT_DISABLED: UInt = 0xC0000072u
    const val STATUS_DISK_FULL: UInt = 0xC000007Fu
    const val STATUS_INSUFFICIENT_RESOURCES: UInt = 0xC000009Au
    const val STATUS_PIPE_NOT_AVAILABLE: UInt = 0xC00000ACu
    const val STATUS_INVALID_PIPE_STATE: UInt = 0xC00000ADu
    const val STATUS_PIPE_BUSY: UInt = 0xC00000AEu
    const val STATUS_IO_TIMEOUT: UInt = 0xC00000B5u
    const val STATUS_FILE_IS_A_DIRECTORY: UInt = 0xC00000BAu
    const val STATUS_NOT_SUPPORTED: UInt = 0xC00000BBu
    const val STATUS_INVALID_NETWORK_RESPONSE: UInt = 0xC00000C3u
    const val STATUS_BAD_NETWORK_NAME: UInt = 0xC00000CCu
    const val STATUS_NOT_A_DIRECTORY: UInt = 0xC0000103u
    const val STATUS_DIRECTORY_NOT_EMPTY: UInt = 0xC0000101u
    const val STATUS_FILE_CLOSED: UInt = 0xC0000128u
    const val STATUS_CANCELLED: UInt = 0xC0000120u
    const val STATUS_USER_SESSION_DELETED: UInt = 0xC0000203u
    const val STATUS_NETWORK_NAME_DELETED: UInt = 0xC00000C9u
    const val STATUS_NETWORK_SESSION_EXPIRED: UInt = 0xC000035Cu
    const val STATUS_ACCESS_DISABLED_BY_POLICY_OTHER: UInt = 0xC0000364u

    /** Returns the symbolic name for a known [status] code, or its hexadecimal string representation. */
    fun nameOf(status: UInt): String = when (status) {
        STATUS_SUCCESS -> "STATUS_SUCCESS"
        STATUS_PENDING -> "STATUS_PENDING"
        STATUS_NOTIFY_CLEANUP -> "STATUS_NOTIFY_CLEANUP"
        STATUS_NOTIFY_ENUM_DIR -> "STATUS_NOTIFY_ENUM_DIR"
        STATUS_BUFFER_OVERFLOW -> "STATUS_BUFFER_OVERFLOW"
        STATUS_NO_MORE_FILES -> "STATUS_NO_MORE_FILES"
        STATUS_INVALID_PARAMETER -> "STATUS_INVALID_PARAMETER"
        STATUS_NO_SUCH_FILE -> "STATUS_NO_SUCH_FILE"
        STATUS_END_OF_FILE -> "STATUS_END_OF_FILE"
        STATUS_MORE_PROCESSING_REQUIRED -> "STATUS_MORE_PROCESSING_REQUIRED"
        STATUS_ACCESS_DENIED -> "STATUS_ACCESS_DENIED"
        STATUS_BUFFER_TOO_SMALL -> "STATUS_BUFFER_TOO_SMALL"
        STATUS_OBJECT_NAME_INVALID -> "STATUS_OBJECT_NAME_INVALID"
        STATUS_OBJECT_NAME_NOT_FOUND -> "STATUS_OBJECT_NAME_NOT_FOUND"
        STATUS_OBJECT_NAME_COLLISION -> "STATUS_OBJECT_NAME_COLLISION"
        STATUS_OBJECT_PATH_NOT_FOUND -> "STATUS_OBJECT_PATH_NOT_FOUND"
        STATUS_SHARING_VIOLATION -> "STATUS_SHARING_VIOLATION"
        STATUS_FILE_LOCK_CONFLICT -> "STATUS_FILE_LOCK_CONFLICT"
        STATUS_LOCK_NOT_GRANTED -> "STATUS_LOCK_NOT_GRANTED"
        STATUS_LOGON_FAILURE -> "STATUS_LOGON_FAILURE"
        STATUS_ACCOUNT_RESTRICTION -> "STATUS_ACCOUNT_RESTRICTION"
        STATUS_PASSWORD_EXPIRED -> "STATUS_PASSWORD_EXPIRED"
        STATUS_ACCOUNT_DISABLED -> "STATUS_ACCOUNT_DISABLED"
        STATUS_DISK_FULL -> "STATUS_DISK_FULL"
        STATUS_INSUFFICIENT_RESOURCES -> "STATUS_INSUFFICIENT_RESOURCES"
        STATUS_PIPE_NOT_AVAILABLE -> "STATUS_PIPE_NOT_AVAILABLE"
        STATUS_INVALID_PIPE_STATE -> "STATUS_INVALID_PIPE_STATE"
        STATUS_PIPE_BUSY -> "STATUS_PIPE_BUSY"
        STATUS_IO_TIMEOUT -> "STATUS_IO_TIMEOUT"
        STATUS_FILE_IS_A_DIRECTORY -> "STATUS_FILE_IS_A_DIRECTORY"
        STATUS_NOT_SUPPORTED -> "STATUS_NOT_SUPPORTED"
        STATUS_INVALID_NETWORK_RESPONSE -> "STATUS_INVALID_NETWORK_RESPONSE"
        STATUS_BAD_NETWORK_NAME -> "STATUS_BAD_NETWORK_NAME"
        STATUS_NETWORK_NAME_DELETED -> "STATUS_NETWORK_NAME_DELETED"
        STATUS_DIRECTORY_NOT_EMPTY -> "STATUS_DIRECTORY_NOT_EMPTY"
        STATUS_NOT_A_DIRECTORY -> "STATUS_NOT_A_DIRECTORY"
        STATUS_CANCELLED -> "STATUS_CANCELLED"
        STATUS_FILE_CLOSED -> "STATUS_FILE_CLOSED"
        STATUS_USER_SESSION_DELETED -> "STATUS_USER_SESSION_DELETED"
        STATUS_NETWORK_SESSION_EXPIRED -> "STATUS_NETWORK_SESSION_EXPIRED"
        STATUS_ACCESS_DISABLED_BY_POLICY_OTHER -> "STATUS_ACCESS_DISABLED_BY_POLICY_OTHER"
        else -> "0x${status.toString(16).padStart(8, '0').uppercase()}"
    }
}

/**
 * Exception thrown when an SMB protocol operation fails.
 *
 * @property ntStatus 32-bit `NTSTATUS` code returned by the server or generated locally (`[NtStatus]`).
 */
class SmbException(
    val ntStatus: UInt,
    message: String = "SMB operation failed with ${NtStatus.nameOf(ntStatus)} (0x${ntStatus.toString(16).padStart(8, '0').uppercase()})",
    cause: Throwable? = null,
) : Exception(message, cause)
